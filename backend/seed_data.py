def seed_database():
    with Session(engine) as session:
        category_map = {}

        for name in categories:
            category = session.scalar(
                select(Category).where(Category.name == name)
            )

            if category is None:
                category = Category(name=name)
                session.add(category)
                session.flush()

            category_map[name] = category.id

        for title, category_name, description in activities:
            exists = session.scalar(
                select(Activity).where(Activity.title == title)
            )

            if exists is None:
                activity = Activity(
                    title=title,
                    description=description,
                    category_id=category_map[category_name],
                    location="ЯГТУ",
                    participation_info="Информация об участии уточняется"
                )

                session.add(activity)

        session.commit()

    print("Демонстрационные данные успешно добавлены")


if __name__ == "__main__":
    seed_database()
